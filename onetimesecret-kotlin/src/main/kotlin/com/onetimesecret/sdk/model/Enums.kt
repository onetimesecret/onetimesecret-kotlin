package com.onetimesecret.sdk.model

import com.onetimesecret.sdk.internal.FallbackEnumSerializer
import kotlinx.serialization.Serializable

/**
 * Lifecycle state of a secret (the recipient-facing record).
 *
 * [UNKNOWN] is returned by status checks for identifiers the service does not
 * recognise, and is also the fallback for any state this SDK version does not
 * know about.
 */
@Serializable(with = SecretState.Serializer::class)
public enum class SecretState(
    public val wireName: String,
) {
    NEW("new"),
    PREVIEWED("previewed"),
    REVEALED("revealed"),
    BURNED("burned"),
    UNKNOWN("unknown"),
    ;

    internal object Serializer :
        FallbackEnumSerializer<SecretState>("SecretState", entries.toTypedArray(), UNKNOWN, SecretState::wireName)
}

/**
 * Lifecycle state of a receipt (the creator-facing record).
 *
 * [UNKNOWN] is the fallback for any state this SDK version does not know about.
 */
@Serializable(with = ReceiptState.Serializer::class)
public enum class ReceiptState(
    public val wireName: String,
) {
    NEW("new"),
    SHARED("shared"),
    PREVIEWED("previewed"),
    REVEALED("revealed"),
    BURNED("burned"),
    EXPIRED("expired"),
    ORPHANED("orphaned"),
    UNKNOWN("unknown"),
    ;

    internal object Serializer :
        FallbackEnumSerializer<ReceiptState>("ReceiptState", entries.toTypedArray(), UNKNOWN, ReceiptState::wireName)
}

/** How the secret value should be rendered when revealed. */
@Serializable(with = DisplayType.Serializer::class)
public enum class DisplayType(
    public val wireName: String,
) {
    TEXT("text"),
    MARKDOWN("markdown"),
    ;

    internal object Serializer :
        FallbackEnumSerializer<DisplayType>("DisplayType", entries.toTypedArray(), TEXT, DisplayType::wireName)
}

/** Whether a secret was created from a caller-provided value or generated by the service. */
@Serializable(with = SecretKind.Serializer::class)
public enum class SecretKind(
    public val wireName: String,
) {
    CONCEAL("conceal"),
    GENERATE("generate"),
    UNKNOWN("unknown"),
    ;

    internal object Serializer :
        FallbackEnumSerializer<SecretKind>("SecretKind", entries.toTypedArray(), UNKNOWN, SecretKind::wireName)
}
