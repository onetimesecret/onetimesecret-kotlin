// ---------------------------------------------------------------------------
// Generate BuildInfo.kt from the Gradle version so the User-Agent string and
// `OnetimeSecret.VERSION` can never drift from what is published.
// ---------------------------------------------------------------------------
val generateBuildInfo =
    tasks.register("generateBuildInfo") {
        val outputDir = layout.buildDirectory.dir("generated/source/buildInfo/kotlin")
        val versionName = providers.gradleProperty("VERSION_NAME").get()
        inputs.property("version", versionName)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().file("com/onetimesecret/sdk/internal/BuildInfo.kt").asFile
            file.parentFile.mkdirs()
            file.writeText(
                """
                |// Generated by the generateBuildInfo Gradle task. Do not edit.
                |package com.onetimesecret.sdk.internal
                |
                |internal object BuildInfo {
                |    const val VERSION: String = "$versionName"
                |}
                |
                """.trimMargin(),
            )
        }
    }

kotlin.sourceSets.named("main") {
    kotlin.srcDir(generateBuildInfo)
}

tasks.withType<Test>().configureEach {
    useJUnitPlatform()
    // Gradle runs tests with assertions enabled, which switches kotlinx.coroutines
    // into debug mode and makes it wrap every exception that crosses a
    // suspension in a copy of itself (the original becomes the cause). No
    // consumer sees that, so turn it off and let tests assert on the real
    // cause chain.
    systemProperty("kotlinx.coroutines.stacktrace.recovery", "false")
    testLogging {
        events("failed", "skipped")
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}

