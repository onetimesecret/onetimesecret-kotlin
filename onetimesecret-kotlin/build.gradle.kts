description = "Official Kotlin SDK for the Onetime Secret API (Android and JVM)"

kotlin {
    // Every public declaration must carry an explicit visibility modifier and
    // return type; the compiler rejects accidental API surface.
    explicitApi()

    jvmToolchain(
        libs.versions.java.toolchain
            .get()
            .toInt(),
    )

    compilerOptions {
        // The Kotlin floor the README promises. Pinning the language and API
        // level keeps the emitted metadata readable by that compiler even
        // after the Kotlin plugin is bumped; raise these and the README together.
        languageVersion.set(KotlinVersion.KOTLIN_2_4)
        apiVersion.set(KotlinVersion.KOTLIN_2_4)

        // Android-friendly bytecode. The build runs on a 17 toolchain but emits
        // class files any AGP 8.x project can consume without extra desugaring.
        jvmTarget.set(JvmTarget.JVM_11)
        allWarningsAsErrors.set(true)
        jvmDefault.set(JvmDefaultMode.NO_COMPATIBILITY)
        freeCompilerArgs.addAll("-Xjdk-release=11")
    }
}

java {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
}

// Tests run on the 17 toolchain (JUnit 6 needs it) while the library itself
// stays at 11: raise the target for the test compilation and its classpaths.
val testJvmTarget =
    libs.versions.java.toolchain
        .get()
        .toInt()
tasks.named<KotlinCompile>("compileTestKotlin") {
    compilerOptions {
        jvmTarget.set(JvmTarget.fromTarget(testJvmTarget.toString()))
        freeCompilerArgs.set(listOf("-Xjdk-release=$testJvmTarget"))
    }
}
tasks.named<JavaCompile>("compileTestJava") {
    sourceCompatibility = testJvmTarget.toString()
    targetCompatibility = testJvmTarget.toString()
}
configurations.matching { it.name.startsWith("test") }.configureEach {
    attributes.attribute(TargetJvmVersion.TARGET_JVM_VERSION_ATTRIBUTE, testJvmTarget)
}

